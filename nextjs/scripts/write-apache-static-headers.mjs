import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const STATIC_EXPORT_DIR = process.env.G5_NEXT_DIST_DIR?.trim() || 'out';
const OUT_DIR = join(ROOT, STATIC_EXPORT_DIR);
const NEXT_STATIC_DIR = join(OUT_DIR, '_next', 'static');

// Production security headers. Kept in sync with the server runtime headers in
// next.config.ts (which do NOT apply under `output: export`). connect-src/img-src
// use the `https:` wildcard so headless API hosts need no per-env entry.
const PG_FRAME_SOURCES = [
  'https://*.tosspayments.com',
  'https://testpay.kcp.co.kr',
  'https://*.kcp.co.kr',
  'https://stdpay.inicis.com',
  'https://stgstdpay.inicis.com',
  'https://*.inicis.com',
  'https://web.nicepay.co.kr',
  'https://*.nicepay.co.kr',
].join(' ');
const PG_SCRIPT_SOURCES = PG_FRAME_SOURCES;
const POSTCODE_FRAME_SOURCES = ['https://postcode.map.daum.net', 'https://postcode.map.kakao.com'].join(' ');
const POSTCODE_SCRIPT_SOURCES = 'https://t1.daumcdn.net http://t1.daumcdn.net';
const POSTCODE_IMAGE_SOURCES = 'https://t1.daumcdn.net http://t1.daumcdn.net https://t1.kakaocdn.net';
const SCRIPT_SOURCES = [
  `'self'`,
  `'unsafe-inline'`,
  ...(process.env.NEXT_CSP_ALLOW_UNSAFE_EVAL === '1' ? [`'unsafe-eval'`] : []),
  'https://js.tosspayments.com',
  PG_SCRIPT_SOURCES,
  POSTCODE_SCRIPT_SOURCES,
].join(' ');

const CSP = [
  `default-src 'self'`,
  `script-src ${SCRIPT_SOURCES}`,
  `style-src 'self' 'unsafe-inline'`,
  `img-src 'self' blob: data: https: ${POSTCODE_IMAGE_SOURCES}`,
  `font-src 'self' data:`,
  `connect-src 'self' https:`,
  `frame-src ${PG_FRAME_SOURCES} ${POSTCODE_FRAME_SOURCES}`,
  `frame-ancestors 'none'`,
  `base-uri 'self'`,
  `form-action 'self' ${PG_FRAME_SOURCES}`,
  `object-src 'none'`,
].join('; ');

const SECURITY_HEADERS = `
  Header set X-Content-Type-Options "nosniff"
  Header set X-Frame-Options "DENY"
  Header set Referrer-Policy "strict-origin-when-cross-origin"
  Header set Permissions-Policy "camera=(), microphone=(), geolocation=()"
  Header set Strict-Transport-Security "max-age=31536000; includeSubDomains"
  Header set Content-Security-Policy "${CSP}"`;

const APP_HTACCESS = `
# Generated by nextjs/scripts/write-apache-static-headers.mjs.
# Applies to files served from theme/nextjs_default/.

<IfModule mod_mime.c>
  AddType application/manifest+json .webmanifest
  AddType text/javascript .js
  AddType text/css .css
  AddType image/svg+xml .svg
</IfModule>

<IfModule mod_headers.c>
${SECURITY_HEADERS}

  <FilesMatch "\\.(html|txt)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>

  <FilesMatch "^(sw\\.js|manifest\\.json|manifest\\.webmanifest|robots\\.txt|sitemap\\.xml)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>

  <FilesMatch "^(favicon\\.ico|icon-[0-9]+\\.png|og-default\\.png)$">
    Header set Cache-Control "public, max-age=86400"
  </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/plain text/css text/javascript application/javascript application/json application/manifest+json application/xml image/svg+xml
</IfModule>
`;

const NEXT_STATIC_HTACCESS = `
# Generated by nextjs/scripts/write-apache-static-headers.mjs.
# Next.js static chunks are content-hashed and safe to cache for a year.

<IfModule mod_headers.c>
  Header set X-Content-Type-Options "nosniff"
  Header set Cache-Control "public, max-age=31536000, immutable"
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/css text/javascript application/javascript application/json image/svg+xml
</IfModule>
`;

function fail(message) {
  console.error(`[write-apache-static-headers] ${message}`);
  process.exit(1);
}

if (!existsSync(join(OUT_DIR, 'index.html'))) {
  console.log(`[write-apache-static-headers] skipped; no static export at ${STATIC_EXPORT_DIR}`);
  process.exit(0);
}

if (!existsSync(NEXT_STATIC_DIR)) {
  fail('Missing nextjs/out/_next/static. Run `npm run build` first.');
}

writeFileSync(join(OUT_DIR, '.htaccess'), `${APP_HTACCESS.trim()}\n`, 'utf8');
mkdirSync(NEXT_STATIC_DIR, { recursive: true });
writeFileSync(join(NEXT_STATIC_DIR, '.htaccess'), `${NEXT_STATIC_HTACCESS.trim()}\n`, 'utf8');

console.log(`[write-apache-static-headers] wrote ${STATIC_EXPORT_DIR}/.htaccess and ${STATIC_EXPORT_DIR}/_next/static/.htaccess`);
