#!/usr/bin/env node
// Generates src/types/api.gen.ts from the Django OpenAPI schema (../openapi/schema.json).
//   node scripts/api-types.mjs          write the file
//   node scripts/api-types.mjs --check  fail when the committed file is out of date (CI)
// Regenerate the schema first: python manage.py spectacular --format openapi-json --file openapi/schema.json
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = path.resolve(root, "..", "openapi", "schema.json");
const outputPath = path.join(root, "src", "types", "api.gen.ts");
const header = [
  "/**",
  " * Generated by scripts/api-types.mjs from openapi/schema.json (drf-spectacular). Do not edit.",
  " * Typed v1 responses are declared in gnu_jango/api/contracts/ and checked by contract tests.",
  " */",
  "",
  "",
].join("\n");

const ast = await openapiTS(pathToFileURL(schemaPath));
const generated = header + astToString(ast);

if (process.argv.includes("--check")) {
  const committed = await readFile(outputPath, "utf8").catch(() => "");
  if (committed.replace(/\r\n/g, "\n") !== generated) {
    console.error(
      "src/types/api.gen.ts does not match openapi/schema.json. Run `npm run api:types` and commit the result."
    );
    process.exit(1);
  }
  console.log("API types match openapi/schema.json.");
} else {
  await writeFile(outputPath, generated);
  console.log(`Wrote ${path.relative(root, outputPath)}`);
}
